"""Generate shared/fonts.js from BUSY Bar firmware pixel fonts.

The firmware converts each TTF with lv_font_conv at size 16. Every font uses
16 units per em, so one font unit is one display pixel and the bitmaps below
match what the firmware draws for the same font name.

Usage (requires Pillow and fontTools):
  python3 scripts/extract-fonts.py /path/to/busybar-firmware/assets/shared/fonts/ttf
"""

import json
import sys
from pathlib import Path

from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

# API font name -> firmware TTF (applications/services/web_server/http_api/api_display.c)
FONTS = {
    'small': 'busy_regular_5px',
    'normal': 'busy_regular_7px',
    'condensed': 'busy_condensed_7px',
    'extra_large': 'busy_bold_10px',
}
CHARS = ''.join(chr(c) for c in range(0x20, 0x7F)) + '°…·'
FIRMWARE = '1.3.1'


def glyph(font, ch, ascent, height):
    image = Image.new('1', (48, 48), 0)
    draw = ImageDraw.Draw(image)
    draw.fontmode = '1'
    draw.text((8, 16), ch, font=font, fill=1, anchor='ls')
    box = image.getbbox()
    assert not box or (box[0] >= 8 and box[2] <= 20), f'{ch!r} exceeds the 12-pixel record'
    rows = [
        sum(1 << (15 - x) for x in range(16) if image.getpixel((8 + x, 16 - ascent + y)))
        for y in range(height)
    ]
    width = max([16 - (r & -r).bit_length() + 1 for r in rows if r] + [0])
    return width, [r >> (16 - width) if width else 0 for r in rows]


def main(ttf_dir):
    out = [
        '// Generated by scripts/extract-fonts.py from BUSY Bar firmware ' + FIRMWARE + ' fonts.',
        '// Do not edit. Each record: advance and width (one hex digit each), then one 3-digit hex row per line.',
        'export const CHARS = ' + json.dumps(CHARS, ensure_ascii=False) + ';',
        'export const FONTS = {',
    ]
    for name, file in FONTS.items():
        path = Path(ttf_dir) / (file + '.ttf')
        ttf = TTFont(path)
        cmap, hmtx, hhea = ttf.getBestCmap(), ttf['hmtx'], ttf['hhea']
        ascent, height, cap = hhea.ascent, hhea.ascent - hhea.descent, ttf['OS/2'].sCapHeight
        font = ImageFont.truetype(str(path), 16)
        data = ''
        for ch in CHARS:
            code = ord(ch) if ord(ch) in cmap else ord('?')
            advance = hmtx[cmap[code]][0]
            width, rows = glyph(font, chr(code), ascent, height)
            assert advance < 16
            data += format(advance, 'x') + format(width, 'x') + ''.join(f'{r:03x}' for r in rows)
        out.append(f'  {name}: {{ height: {height}, ascent: {ascent}, cap: {cap}, data: "{data}" }},')
    out.append('};')
    Path(__file__).resolve().parent.parent.joinpath('shared/fonts.js').write_text('\n'.join(out) + '\n')


if __name__ == '__main__':
    main(sys.argv[1])
